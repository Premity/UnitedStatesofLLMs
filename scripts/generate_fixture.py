"""Generate the frontend replay fixture from the real Pydantic models (F1).

This is a *stand-in* for `record_fixture.py`, which records an actual debate.
Recording needs four reachable models; this needs nothing but the repo, so the
frontend track is not blocked on the model roster.

What is real here:

  * the event envelope and sequence — `start -> turn* -> verdict -> done`,
    matching `app.routers.debate.stream_debate`
  * every payload shape — built as `Turn` / `Verdict` / `Objection` instances
    and serialised with the same `model_dump_json()` the router uses, so a
    field rename in council-core changes this output too
  * every citation status — produced by running the real `CitationResolver`
    against the real `data/index/citation_index.json`, not hand-asserted
  * the corpus text behind each resolved citation — read from that index

What is invented: the prose. Claims, reasoning, and dispositions are written to
be plausible for the Galić test case, not generated by a model.

    uv run python scripts/generate_fixture.py

Writes runtime/frontend/src/fixtures/sample-run.json in the same format
`record_fixture.py` writes, so swapping in a real recording is a file move.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from datetime import UTC, datetime, timedelta
from pathlib import Path

from council_core.citations import CitationResolver
from council_core.citations.resolver import JsonCorpusIndex
from council_core.models.citation import Citation, CitationType
from council_core.models.debate import (
    Argument,
    Objection,
    ObjectionDisposition,
    Role,
    Turn,
    Verdict,
)

ROOT = Path(__file__).resolve().parents[1]
INDEX = ROOT / "data/index/citation_index.json"
OUT = ROOT / "runtime/frontend/src/fixtures/sample-run.json"

RUN_ID = "run_f1xtur3g3n0"
ROUND = 1

# Wall-clock is faked so the fixture is byte-stable across regenerations: a
# diff should mean the models changed, not that time passed.
T0 = datetime(2026, 11, 1, 12, 0, 0, tzinfo=UTC)

MODELS = {
    Role.PRESENTER: "groq/openai/gpt-oss-120b",
    Role.ATTACKER_DOCTRINAL: "ollama/qwen3.5:14b",
    Role.ATTACKER_EVIDENTIARY: "ollama/gemma3:12b",
    Role.JUDGE: "gemini/gemini-3.1-pro-preview",
}

# Stand-in for the SHA-256 of a rendered prompt. Real recordings carry the true
# hash; nothing in the frontend reads it, but the field must be present.
PROMPT_HASH = "0" * 64


def treaty(instrument: str, article: str, *, quote: str | None = None) -> Citation:
    return Citation(
        type=CitationType.TREATY,
        instrument=instrument,
        article=article,
        quoted_text=quote,
    )


def case(case_id: str, paragraph: str) -> Citation:
    return Citation(
        type=CitationType.CASE, case_id=case_id, instrument=case_id, paragraph=paragraph
    )


def customary(rule: int) -> Citation:
    return Citation(type=CitationType.CUSTOMARY, instrument="customary_ihl", rule_number=rule)


def build_turns(resolve) -> tuple[list[Turn], Verdict]:
    """Assemble the debate record. `resolve` is the real resolver's resolve_all."""

    # ── Presenter ────────────────────────────────────────────────────────────
    # Three arguments: two resting on indexed treaty text, one reaching for a
    # judgment the corpus does not contain.
    a1_cites = [treaty("ap_i", "51(2)")]
    a1 = Argument(
        id="arg_terror_prohibition",
        claim=(
            "A campaign of sniping and shelling whose primary purpose is to spread terror "
            "among civilians violates the prohibition in Article 51(2) of Additional Protocol I."
        ),
        reasoning=(
            "Article 51(2) contains two distinct prohibitions. The first protects civilians "
            "from being made the object of attack. The second is wider: it forbids acts or "
            "threats of violence whose primary purpose is to spread terror, and it does not "
            "require that any particular attack be unlawful on other grounds. A sustained "
            "campaign undertaken for that purpose therefore falls squarely within it."
        ),
        citations=a1_cites,
        resolved_citations=resolve(a1_cites),
    )

    a2_cites = [treaty("ap_i", "51(4)"), treaty("ap_i", "85(3)(a)")]
    a2 = Argument(
        id="arg_indiscriminate",
        claim=(
            "The same conduct constitutes an indiscriminate attack and, where it causes death, "
            "a grave breach."
        ),
        reasoning=(
            "Shelling directed at civilian areas of a besieged city does not distinguish "
            "between military objectives and civilians, which Article 51(4) prohibits. "
            "Article 85(3)(a) makes making the civilian population the object of attack a "
            "grave breach when committed wilfully and causing death or serious injury."
        ),
        citations=a2_cites,
        resolved_citations=resolve(a2_cites),
    )

    a3_cites = [case("icty_galic_tj", "58")]
    a3 = Argument(
        id="arg_jurisprudence",
        claim=(
            "The Tribunal has held that terror against a civilian population is a violation "
            "of the laws or customs of war attracting individual criminal responsibility."
        ),
        reasoning=(
            "The trial judgment treats the terror prohibition as customary and as giving rise "
            "to individual criminal liability, which answers the objection that Article 51(2) "
            "binds states but not persons."
        ),
        citations=a3_cites,
        resolved_citations=resolve(a3_cites),
    )

    presenter = Turn(
        id="turn_presenter_r1",
        round_number=ROUND,
        role=Role.PRESENTER,
        model_id=MODELS[Role.PRESENTER],
        prompt_id="presenter/opening",
        prompt_hash=PROMPT_HASH,
        arguments=[a1, a2, a3],
        raw_response="[generated fixture — no model output]",
        started_at=T0,
        completed_at=T0 + timedelta(seconds=41),
        prompt_tokens=3180,
        completion_tokens=842,
    )

    # ── Doctrinal attacker ───────────────────────────────────────────────────
    # One objection cites an article that does not exist in an instrument we
    # *did* index: the fabrication signal the UI must show loudly.
    o1_cites = [treaty("ap_i", "51(3)"), treaty("ap_i", "51(9)")]
    o1 = Objection(
        id="obj_treaty_applicability",
        raised_by=Role.ATTACKER_DOCTRINAL,
        target_argument_id=a1.id,
        ground=(
            "Additional Protocol I governs international armed conflict; its application to "
            "a siege within a single state is not established."
        ),
        reasoning=(
            "Article 1 limits the Protocol's field of application. If the conflict is "
            "non-international, Article 51(2) does not apply of its own force and the "
            "argument must rest on Additional Protocol II or on custom. Article 51(9) "
            "further confines the reach of this Part."
        ),
        citations=o1_cites,
        resolved_citations=resolve(o1_cites),
        disposition=ObjectionDisposition.OVERRULED,
        disposition_reasoning=(
            "The terror prohibition is customary and applies in both international and "
            "non-international armed conflict, so the characterisation of the conflict does "
            "not dispose of the claim. The objection also cites Article 51(9), which does "
            "not exist; Article 51 ends at paragraph 8."
        ),
    )

    o2_cites = [treaty("ap_i", "51(5)(b)"), treaty("ap_i", "57(2)(a)(iii)")]
    o2 = Objection(
        id="obj_proportionality",
        raised_by=Role.ATTACKER_DOCTRINAL,
        target_argument_id=a2.id,
        ground=(
            "Characterising the attacks as indiscriminate skips the proportionality "
            "assessment each individual attack requires."
        ),
        reasoning=(
            "Articles 51(5)(b) and 57(2)(a)(iii) frame an attack's lawfulness in relation to "
            "the concrete and direct military advantage anticipated at the time. A besieged "
            "city contains military objectives, so an aggregate finding cannot substitute "
            "for that assessment."
        ),
        citations=o2_cites,
        resolved_citations=resolve(o2_cites),
        disposition=ObjectionDisposition.PARTIAL,
        disposition_reasoning=(
            "Sound as to the indiscriminate-attack argument, which is narrowed accordingly. "
            "It does not reach the terror claim, where purpose rather than proportionality "
            "is the operative question."
        ),
    )

    doctrinal = Turn(
        id="turn_doctrinal_r1",
        round_number=ROUND,
        role=Role.ATTACKER_DOCTRINAL,
        model_id=MODELS[Role.ATTACKER_DOCTRINAL],
        prompt_id="attacker_doctrinal/challenge",
        prompt_hash=PROMPT_HASH,
        objections=[o1, o2],
        raw_response="[generated fixture — no model output]",
        started_at=T0 + timedelta(seconds=41),
        completed_at=T0 + timedelta(seconds=118),
        prompt_tokens=4210,
        completion_tokens=1104,
    )

    # ── Evidentiary attacker ─────────────────────────────────────────────────
    # The misquote: a locator that resolves, attached to text that does not
    # match what the corpus actually says.
    o3_cites = [
        treaty(
            "ap_i",
            "51(2)",
            quote=(
                "Attacks against the civilian population are prohibited in all circumstances "
                "and without exception, regardless of military necessity."
            ),
        )
    ]
    o3 = Objection(
        id="obj_misquote",
        raised_by=Role.ATTACKER_EVIDENTIARY,
        target_argument_id=a1.id,
        ground="The presenter's reading overstates what Article 51(2) says.",
        reasoning=(
            "The provision does not contain an absolute, exceptionless prohibition framed "
            "against military necessity. Resting the case on wording the instrument does not "
            "use weakens it."
        ),
        citations=o3_cites,
        resolved_citations=resolve(o3_cites),
        disposition=ObjectionDisposition.SUSTAINED,
        disposition_reasoning=(
            "The quoted wording does not appear in Article 51(2). The presenter's own "
            "reasoning, however, tracks the actual text, so the defect is in the quotation "
            "rather than the argument."
        ),
    )

    o4_cites = [case("icty_galic_tj", "769"), customary(156)]
    o4 = Objection(
        id="obj_evidentiary_basis",
        raised_by=Role.ATTACKER_EVIDENTIARY,
        target_argument_id=a3.id,
        ground=(
            "The factual predicate does not establish that spreading terror was the primary "
            "purpose rather than an effect."
        ),
        reasoning=(
            "Article 51(2) turns on primary purpose. The stated facts describe sustained "
            "sniping and shelling over 23 months but do not identify the evidence from which "
            "purpose is inferred — orders, patterns of targeting, or statements of intent. "
            "Without that, the terror finding is asserted rather than shown."
        ),
        citations=o4_cites,
        resolved_citations=resolve(o4_cites),
        disposition=ObjectionDisposition.OVERRULED,
        disposition_reasoning=(
            "Purpose may be inferred from the pattern and duration of the attacks, and the "
            "facts as given describe a campaign rather than isolated incidents. The objection "
            "is noted as a limit on the confidence attached to the holding, and both "
            "authorities it cites are outside the indexed corpus and so unverified here."
        ),
    )

    evidentiary = Turn(
        id="turn_evidentiary_r1",
        round_number=ROUND,
        role=Role.ATTACKER_EVIDENTIARY,
        model_id=MODELS[Role.ATTACKER_EVIDENTIARY],
        prompt_id="attacker_evidentiary/challenge",
        prompt_hash=PROMPT_HASH,
        objections=[o3, o4],
        raw_response="[generated fixture — no model output]",
        started_at=T0 + timedelta(seconds=41),
        completed_at=T0 + timedelta(seconds=131),
        prompt_tokens=4180,
        completion_tokens=967,
    )

    # ── Judge ────────────────────────────────────────────────────────────────
    verdict = Verdict(
        conclusion=(
            "A sustained campaign of sniping and shelling directed at civilians with the "
            "primary purpose of spreading terror violates the laws or customs of war."
        ),
        reasoning=(
            "The prohibition in Article 51(2) of Additional Protocol I is twofold, and its "
            "second limb turns on the purpose of the violence rather than on the lawfulness "
            "of any single attack. That limb is customary and applies irrespective of how the "
            "conflict is characterised, which disposes of the applicability objection. The "
            "indiscriminate-attack argument is narrowed: an aggregate finding cannot replace "
            "the proportionality assessment each attack requires, and it is retained only as "
            "to attacks for which no military objective is identified. The terror holding "
            "does not depend on it.\n\n"
            "Purpose is established here by the duration and pattern of the attacks rather "
            "than by direct evidence of intent, and the evidentiary objection on that point "
            "is recorded in dissent. The supporting jurisprudence could not be verified "
            "against the corpus, so the holding rests on the treaty text and custom."
        ),
        confidence=0.78,
        confidence_reasoning=(
            "The legal proposition is well settled and the treaty text was verified directly. "
            "Confidence is held below 0.9 because the inference of primary purpose rests on "
            "the pattern of conduct rather than direct evidence, and because the cited "
            "judgment is outside the indexed corpus and could not be checked."
        ),
        surviving_argument_ids=[a1.id, a2.id],
        dissent=[o1, o4],
    )

    judge = Turn(
        id="turn_judge_r1",
        round_number=ROUND,
        role=Role.JUDGE,
        model_id=MODELS[Role.JUDGE],
        prompt_id="judge/rule",
        prompt_hash=PROMPT_HASH,
        raw_response="[generated fixture — no model output]",
        started_at=T0 + timedelta(seconds=131),
        completed_at=T0 + timedelta(seconds=196),
        prompt_tokens=6420,
        completion_tokens=1388,
    )

    return [presenter, doctrinal, evidentiary, judge], verdict


def main(args: argparse.Namespace) -> None:
    index = JsonCorpusIndex(INDEX)
    index.load()
    resolver = CitationResolver(index)

    turns, verdict = build_turns(resolver.resolve_all)

    # Same envelope and ordering as app.routers.debate.stream_debate.
    events: list[dict[str, object]] = [{"event": "start", "data": {"run_id": RUN_ID}}]
    for turn in turns:
        events.append({"event": "turn", "data": json.loads(turn.model_dump_json())})
    events.append({"event": "verdict", "data": json.loads(verdict.model_dump_json())})
    events.append({"event": "done", "data": {"run_id": RUN_ID, "status": "completed"}})

    statuses = Counter(
        rc["status"]
        for e in events
        if e["event"] == "turn"
        for item in e["data"]["arguments"] + e["data"]["objections"]  # type: ignore[index]
        for rc in item["resolved_citations"]
    )

    print(f"index:      {INDEX.relative_to(ROOT)}")
    print(f"sequence:   {' -> '.join(dict.fromkeys(e['event'] for e in events))}")
    print(f"turns:      {len(turns)}")
    print(f"objections: {sum(len(t.objections) for t in turns)}")
    print(f"dissent:    {len(verdict.dissent)}")
    print(f"citations:  {dict(statuses)}")

    # The fixture exists to exercise the UI's four citation states. If the index
    # on disk changes shape, a status can silently vanish — fail instead.
    missing = {"resolved", "unresolved", "out_of_corpus", "misquoted"} - set(statuses)
    if missing:
        print(f"\nNot written: no citation resolved as {', '.join(sorted(missing))}.")
        print("The corpus index may be missing or partial — try: make index-local")
        raise SystemExit(1)

    if args.check:
        existing = json.loads(OUT.read_text(encoding="utf-8")) if OUT.exists() else None
        if existing == events:
            print("\nup to date")
            return
        print("\nstale: regenerate with `uv run python scripts/generate_fixture.py`")
        raise SystemExit(1)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(events, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"\nwrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument(
        "--check",
        action="store_true",
        help="verify the committed fixture matches what this script would write",
    )
    main(p.parse_args())
